#!/usr/bin/env python3
"""Compile assets/music.txt into build/music.c and music.h

Usage: gen_music.py <build dir> <music.txt>

The streams go to build/music.bin, which gen_assets.py puts in the data
(bank 1); src/tune.c copies the tune it plays into a buffer in bank 0
(TUNE_MAX bytes). Each voice of a tune becomes a byte stream:
    $00-$7F n, d    note n (MIDI: 60 is middle C) for d ticks
    $80 d           a rest of d ticks
    $81 i           instrument i from now on
    $FE             back to the start of the voice (a looping tune)
    $FF             the end
"""
import os
import re
import sys

WAVES = {'tri': 0x10, 'saw': 0x20, 'pulse': 0x40, 'noise': 0x80}
NOTES = {'c': 0, 'd': 2, 'e': 4, 'f': 5, 'g': 7, 'a': 9, 'b': 11}


def note(tok, where):
    m = re.fullmatch(r'([a-g])(#?)(\d)', tok)
    if not m:
        sys.exit("%s: not a note: %s" % (where, tok))
    n = 12 * (int(m.group(3)) + 1) + NOTES[m.group(1)] + (1 if m.group(2) else 0)
    if not 0 <= n < 128:
        sys.exit("%s: out of range: %s" % (where, tok))
    return n


def main():
    out, src = sys.argv[1], sys.argv[2]
    lines, cont = [], ''
    for i, raw in enumerate(open(src), 1):
        line = raw.split(';')[0].rstrip()
        if line.endswith('\\'):
            cont += line[:-1] + ' '
            continue
        line = cont + line
        cont = ''
        if line.strip():
            lines.append((i, line.strip()))
    instruments, tunes = [], []
    for i, line in lines:
        w = line.split()
        if w[0] == 'instrument':
            name, wave, ad, sr, pw, vib, gap = w[1:]
            instruments.append((name, WAVES[wave], int(ad, 16), int(sr, 16), int(pw, 16), int(vib), int(gap)))
        elif w[0] == 'tune':
            tunes.append({'name': w[1], 'fpt': int(w[2]), 'loop': w[3] == 'loop', 'voices': []})
        elif re.fullmatch(r'v[123]:', w[0]):
            tunes[-1]['voices'].append((i, w[1:]))
        else:
            sys.exit("%s:%d: what is %s?" % (src, i, w[0]))
    inst_id = {ins[0]: k for k, ins in enumerate(instruments)}
    data, table = [], []
    for t in tunes:
        if len(t['voices']) != 3:
            sys.exit("tune %s: 3 voices, not %d" % (t['name'], len(t['voices'])))
        lengths = []
        for i, toks in t['voices']:
            table.append(len(data))
            ticks = 0
            for tok in toks:
                where = "%s:%d" % (src, i)
                if tok == '|':
                    continue
                if tok.startswith('@'):
                    data += [0x81, inst_id[tok[1:]]]
                    continue
                name, _, d = tok.partition(':')
                d = int(d)
                if not 0 < d < 256:
                    sys.exit("%s: a length of %d" % (where, d))
                data += ([0x80, d] if name == 'r' else [note(name, where), d])
                ticks += d
            data.append(0xFE if t['loop'] else 0xFF)
            lengths.append(ticks)
        if len(set(lengths)) != 1:
            sys.exit("tune %s: the voices are %s ticks long" % (t['name'], lengths))

    with open(os.path.join(out, 'music.h'), 'w') as f:
        f.write("/* generated by tools/gen_music.py from assets/music.txt - do not edit */\n#pragma once\n\n")
        for k, t in enumerate(tunes):
            f.write("#define TUNE_%s %d\n" % (t['name'].upper(), k))
        f.write("#define NTUNES %d\n#define NINSTRUMENTS %d\n\n" % (len(tunes), len(instruments)))
        sizes = [(table[k * 3 + 3] if k * 3 + 3 < len(table) else len(data)) - table[k * 3] for k in range(len(tunes))]
        f.write("#define TUNE_MAX %d                 /* the largest tune, bytes */\n" % max(sizes))
        f.write("extern const unsigned int mus_voice[NTUNES * 3];     /* each voice's start in the streams (music.bin) */\n")
        f.write("extern const unsigned int mus_size[NTUNES];          /* each tune's bytes */\n")
        f.write("extern const unsigned char mus_fpt[NTUNES];          /* frames per tick */\n")
        f.write("extern const unsigned char ins_wave[NINSTRUMENTS], ins_ad[NINSTRUMENTS], ins_sr[NINSTRUMENTS],\n"
                "    ins_vib[NINSTRUMENTS], ins_gap[NINSTRUMENTS];\n")
        f.write("extern const unsigned int ins_pw[NINSTRUMENTS];\n")

    def arr(ctype, name, vals, per=16):
        rows = [", ".join(str(v) for v in vals[k:k + per]) for k in range(0, len(vals), per)]
        return "const %s %s[%d] = {\n    %s,\n};\n" % (ctype, name, len(vals), ",\n    ".join(rows))

    with open(os.path.join(out, 'music.c'), 'w') as f:
        f.write("/* generated by tools/gen_music.py from assets/music.txt - do not edit */\n#include \"music.h\"\n\n")
        f.write(arr("unsigned int", "mus_voice", table))
        f.write(arr("unsigned int", "mus_size", sizes))
        f.write(arr("unsigned char", "mus_fpt", [t['fpt'] for t in tunes]))
        for k, name in enumerate(('wave', 'ad', 'sr')):
            f.write(arr("unsigned char", "ins_" + name, [ins[1 + k] for ins in instruments]))
        f.write(arr("unsigned int", "ins_pw", [ins[4] for ins in instruments]))
        f.write(arr("unsigned char", "ins_vib", [ins[5] for ins in instruments]))
        f.write(arr("unsigned char", "ins_gap", [ins[6] for ins in instruments]))
    open(os.path.join(out, 'music.bin'), 'wb').write(bytes(data))
    print("%d tunes, %d bytes" % (len(tunes), len(data)))


if __name__ == "__main__":
    main()
